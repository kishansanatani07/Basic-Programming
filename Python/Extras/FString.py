#To create an f-string, put the letter f (or F) directly before the opening quotation mark and place your variables or code inside curly braces {}


name = "Alice"
age = 25

# Basic variable insertion
print(f"Hello, {name}! You are {age} years old.")
# Output: Hello, Alice! You are 25 years old.


price = 19.99
quantity = 3
print(f"Total cost: ${price * quantity}")
# Output: Total cost: $59.97
